#!/usr/bin/env bash
set -euo pipefail

PROJECT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
KAFKA_ORDER_TOPIC="${KAFKA_ORDER_TOPIC:-confluent-rust-order}"
export KAFKA_BOOTSTRAP_SERVERS="${KAFKA_BOOTSTRAP_SERVERS:-${KAFKA_ADVERTISED_HOST:-localhost}:${KAFKA_PORT:-9092}}"
export KAFKA_MESSAGE_COUNT="${KAFKA_MESSAGE_COUNT:-12}"

KAFKA_TOPIC="${KAFKA_ORDER_TOPIC}-single" KAFKA_PARTITIONS=1 "$PROJECT_DIR/start-kafka.sh"
KAFKA_TOPIC="${KAFKA_ORDER_TOPIC}-single" KAFKA_CLIENTS=3 "$PROJECT_DIR/run.sh" pool
KAFKA_TOPIC="${KAFKA_ORDER_TOPIC}-multi" KAFKA_PARTITIONS=3 "$PROJECT_DIR/start-kafka.sh"
KAFKA_TOPIC="${KAFKA_ORDER_TOPIC}-multi" KAFKA_CLIENTS=3 "$PROJECT_DIR/run.sh" pool
KAFKA_TOPIC="${KAFKA_ORDER_TOPIC}-multi" KAFKA_CLIENTS=3 "$PROJECT_DIR/run.sh" broadcast
KAFKA_TOPIC="${KAFKA_ORDER_TOPIC}-multi" KAFKA_CLIENTS=5 "$PROJECT_DIR/run.sh" pool
KAFKA_TOPIC="${KAFKA_ORDER_TOPIC}-multi" KAFKA_CLIENTS=3 KAFKA_WORKER_THREADS=1 "$PROJECT_DIR/run.sh" pool
